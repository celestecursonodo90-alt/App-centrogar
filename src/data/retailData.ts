export function deriveStockStatus(sku: SkuItem): StockHealthStatus {
  const daysSupply = sku.dailyVelocity > 0 ? sku.onHand / sku.dailyVelocity : 999;
  if (daysSupply < 7 || sku.onHand <= sku.reorderPoint * 0.45) {
    return 'Critical Low';
  }
  if (daysSupply < 14 || sku.onHand <= sku.reorderPoint) {
    return 'Low Stock';
  }
  if (daysSupply > 68) {
    return 'Overstock';
  }
  return 'In Stock';
}

